def save_job(company, job, url):
    # ------------------------------------------------
    # REJECT INVALID JOBS
    # ------------------------------------------------

    title = job.get("title", "").strip()

    if not title:
        print("Skipping job with no title:", url)
        return

    # ------------------------------------------------
    # CHECK IF JOB ALREADY EXISTS
    # ------------------------------------------------

    existing_job = get_existing_job(
        company["company_id"],
        title,
        url
    )


    # ------------------------------------------------
    # GET CLOSING DATE
    # ------------------------------------------------

    closing_date = job.get(
        "closing_date",
        ""
    )


    # ------------------------------------------------
    # NORMALIZE EXPIRY DATE LOCALLY
    # ------------------------------------------------

    expiry_date = normalize_expiry_date(
        closing_date
    )


    # ------------------------------------------------
    # GEMINI FALLBACK
    # ------------------------------------------------

    if not expiry_date and closing_date:

        expiry_date = normalize_expiry_date_with_gemini(
            closing_date
        )


    # ------------------------------------------------
    # JOB ALREADY EXISTS
    # ------------------------------------------------

    if existing_job:

        # --------------------------------------------
        # UPDATE MISSING EXPIRY DATE
        # --------------------------------------------

        existing_expiry = existing_job["expiry_date"]

        if (
            (not existing_expiry or not str(existing_expiry).strip())
            and expiry_date
        ):

            update_existing_job(
                existing_job["id"],
                job,
                expiry_date
            )

            print(
                f"Updated expiry date: "
                f"{title} → {expiry_date}"
            )

        else:

            STATS["duplicates"] += 1

        return


    # ------------------------------------------------
    # NEW JOB
    # ------------------------------------------------

    conn = get_db_connection()

    cur = conn.cursor()

    cur.execute("""
        INSERT INTO jobs(
            title,
            company,
            location,
            description,
            expiry_date,
            long_description,
            company_id,
            url,
            date_found
        )

        VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s)
    """, (

        title,

        company["name"],

        job.get("location", ""),

        job.get("reason", ""),

        expiry_date,

        job.get("description", ""),

        company["company_id"],

        url,

        datetime.now().strftime("%Y-%m-%d")

    ))

    conn.commit()

    conn.close()


    # ------------------------------------------------
    # UPDATE STATISTICS
    # ------------------------------------------------

    STATS["jobs_saved"] += 1




