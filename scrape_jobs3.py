def should_skip_url(url):

    if not url:

        return True


    url = url.strip()


    for prefix in IGNORE_PREFIXES:

        if url.startswith(prefix):

            return True


    lower = url.lower()


    for word in IGNORE_URL_KEYWORDS:

        if word in lower:

            return True


    return False


####################################################
# DOWNLOAD PAGE
####################################################

def download(url):

    if should_skip_url(url):

        return None


    try:

        #
        # Download PDFs using requests
        #

        if url.lower().endswith(".pdf"):

            response = requests.get(

                url,

                headers=HEADERS,

                timeout=30

            )

            if response.status_code != 200:

                return None

            return {

                "type":"pdf",

                "content":response.content

            }


        #
        # Download HTML using Playwright
        #

        with sync_playwright() as p:

            browser = p.chromium.launch(

                headless=True

            )

            context = browser.new_context()

            page = context.new_page()

            page.goto(

                url,

                wait_until="domcontentloaded",

                timeout=PLAYWRIGHT_TIMEOUT

            )

            html = page.content()

            context.close()

            browser.close()

            return {

                "type":"html",

                "content":html

            }


    except PlaywrightTimeout:

        print(

            f"Timeout: {url}"

        )

        return None


    except Exception as e:

        print(

            f"Download failed: {url}"

        )

        print(e)

        return None

