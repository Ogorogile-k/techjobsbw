####################################################

def normalize_expiry_date(date_string):

    """
    Convert common expiry-date formats into
    YYYY-MM-DD.

    This function runs locally and does NOT
    make a Gemini API call.
    """

    if not date_string:
        return ""

    date_string = str(date_string).strip()

    if not date_string:
        return ""


    # ------------------------------------------------
    # Remove common prefixes
    # ------------------------------------------------

    date_string = re.sub(
        r'^(closing date|expiry date|expiration date|'
        r'deadline|applications close|apply by)'
        r'\s*:%s\s*',
        '',
        date_string,
        flags=re.IGNORECASE
    ).strip()


    # ------------------------------------------------
    # Remove ordinal suffixes
    #
    # 1st  -> 1
    # 2nd  -> 2
    # 3rd  -> 3
    # 4th  -> 4
    # ------------------------------------------------

    date_string = re.sub(
        r'(\d{1,2})(st|nd|rd|th)\b',
        r'\1',
        date_string,
        flags=re.IGNORECASE
    )


    # ------------------------------------------------
    # Remove commas
    # ------------------------------------------------

    date_string = date_string.replace(
        ",",
        ""
    )


    # ------------------------------------------------
    # Try common date formats
    # ------------------------------------------------

    formats = [

        # ISO
        "%Y-%m-%d",

        # Year first
        "%Y/%m/%d",
        "%Y.%m.%d",

        # Day first
        "%d/%m/%Y",
        "%d-%m-%Y",
        "%d.%m.%Y",

        # Month first
        "%m/%d/%Y",
        "%m-%d-%Y",
        "%m.%d.%Y",

        # Month names
        "%d %B %Y",
        "%d %b %Y",
        "%B %d %Y",
        "%b %d %Y",

        # Two-digit years
        "%d/%m/%y",
        "%d-%m-%y",
        "%m/%d/%y",
        "%m-%d-%y",

    ]


    for date_format in formats:

        try:

            parsed_date = datetime.strptime(
                date_string,
                date_format
            )

            return parsed_date.strftime(
                "%Y-%m-%d"
            )

        except ValueError:

            continue


    # ------------------------------------------------
    # Python could not recognize the date
    # ------------------------------------------------

    return ""


