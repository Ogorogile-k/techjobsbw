    # DELETE EXPIRED JOBS
    ################################################

    print()

    print("Checking for expired jobs...")

    STATS["expired_deleted"] = delete_expired_jobs()

    print(
        f"Expired jobs deleted: "
        f"{STATS['expired_deleted']}"
    )


