def classify_job(text, url):

    #
    # Don't waste Gemini requests on tiny pages.
    #

    if len(text.strip()) < 250:

        return {

            "is_job": False

        }


    prompt = f"""

You are a Botswana job vacancy detector.

Determine whether the following webpage is an
ACTUAL JOB VACANCY.

Ignore:

- contact pages
- news
- company information
- customer portals
- management pages
- privacy pages
- policy pages

Return ONLY valid JSON.

{{
"is_job": true,
"title":"",
"location":"",
"closing_date":"",
"description":"",
"confidence":0,
"reason":""
}}

URL

{url}

CONTENT

{text[:9000]}

"""

    retries = 3

    while retries > 0:

        try:

            response = client.models.generate_content(

                model=MODEL,

                contents=prompt

            )

            result = response.text

            result = result.replace(

                "```json",

                ""

            )

            result = result.replace(

                "```",

                ""

            )

            result = result.strip()

            return json.loads(result)


        except ClientError as e:

            #
            # Gemini rate limit.
            #

            if "429" in str(e):

                print()

                print(

                    "Gemini rate limit reached."

                )

                print(

                    "Waiting 60 seconds..."

                )

                time.sleep(60)

                retries -= 1

                continue

            print(e)

            return {

                "is_job": False

            }


        except Exception as e:

            print()

            print(

                "Classifier error"

            )

            print(e)

            return {

                "is_job": False

            }


    return {

        "is_job": False

    }


