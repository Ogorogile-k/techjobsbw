def extract_text(page):

    if page is None:

        return ""


    #
    # PDF
    #

    if page["type"] == "pdf":

        try:

            reader = PdfReader(

                BytesIO(

                    page["content"]

                )

            )

            text = ""

            for pdf_page in reader.pages:

                text += (

                    pdf_page.extract_text()

                    or ""

                )

            return text

        except Exception:

            return ""


    #
    # HTML
    #

    soup = BeautifulSoup(

        page["content"],

        "lxml"

    )

    for tag in soup(

        [

            "script",

            "style",

            "header",

            "footer",

            "nav",

            "noscript"

        ]

    ):

        tag.decompose()

    return soup.get_text(

        " ",

        strip=True

    )


