def scan_link(company, url):

    page = download(url)

    if page is None:

        return


    text = extract_text(page)


    #
    # Quick filter before Gemini.
    #

    lower = text.lower()


    indicators = [

        "closing date",

        "vacancy",

        "vacancies",

        "job purpose",

        "minimum requirements",

        "apply",

        "applications",

        "position",

        "employment"

    ]


    if not any(

        word in lower

        for word in indicators

    ):

        return


    result = classify_job(

        text,

        url

    )


    if not result.get(

        "is_job",

        False

    ):

        return


    print_job(

        company,

        result,

        url

    )


    save_job(

        company,

        result,

        url

    )


