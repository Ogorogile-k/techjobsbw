import os
import sqlite3
import psycopg2


SQLITE_DATABASE = "jobs.db"


# ============================================================
# CONNECT TO SQLITE
# ============================================================

sqlite_conn = sqlite3.connect(SQLITE_DATABASE)
sqlite_conn.row_factory = sqlite3.Row
sqlite_cursor = sqlite_conn.cursor()


# ============================================================
# CONNECT TO POSTGRESQL
# ============================================================

database_url = os.getenv("DATABASE_URL")

if not database_url:
    raise RuntimeError(
        "DATABASE_URL environment variable is not set."
    )

postgres_conn = psycopg2.connect(database_url)
postgres_cursor = postgres_conn.cursor()


try:

    # ========================================================
    # CREATE COMPANIES TABLE
    # ========================================================

    postgres_cursor.execute("""
        CREATE TABLE IF NOT EXISTS companies (
            company_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            industry TEXT,
            website TEXT,
            email TEXT,
            phone TEXT,
            headquarters TEXT,
            logo TEXT,
            description TEXT
        );
    """)


    # ========================================================
    # CREATE JOBS TABLE
    # ========================================================

    postgres_cursor.execute("""
        CREATE TABLE IF NOT EXISTS jobs (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title TEXT,
            company TEXT,
            location TEXT,
            description TEXT,
            expiry_date TEXT,
            long_description TEXT,
            company_id INTEGER,
            url TEXT,
            date_found TEXT,
            FOREIGN KEY (company_id)
                REFERENCES companies(company_id)
        );
    """)


    # ========================================================
    # READ COMPANIES FROM SQLITE
    # ========================================================

    sqlite_cursor.execute("""
        SELECT
            company_id,
            name,
            industry,
            website,
            email,
            phone,
            headquarters,
            logo,
            description
        FROM companies
        ORDER BY company_id
    """)

    companies = sqlite_cursor.fetchall()


    # ========================================================
    # INSERT COMPANIES
    # ========================================================

    for company in companies:

        postgres_cursor.execute("""
            INSERT INTO companies (
                company_id,
                name,
                industry,
                website,
                email,
                phone,
                headquarters,
                logo,
                description
            )
            VALUES (
                %s, %s, %s, %s, %s,
                %s, %s, %s, %s
            )
            ON CONFLICT (company_id)
            DO UPDATE SET
                name = EXCLUDED.name,
                industry = EXCLUDED.industry,
                website = EXCLUDED.website,
                email = EXCLUDED.email,
                phone = EXCLUDED.phone,
                headquarters = EXCLUDED.headquarters,
                logo = EXCLUDED.logo,
                description = EXCLUDED.description
        """, tuple(company))


    # ========================================================
    # READ JOBS FROM SQLITE
    # ========================================================

    sqlite_cursor.execute("""
        SELECT
            id,
            title,
            company,
            location,
            description,
            expiry_date,
            long_description,
            company_id,
            url,
            date_found
        FROM jobs
        ORDER BY id
    """)

    jobs = sqlite_cursor.fetchall()


    # ========================================================
    # INSERT JOBS
    # ========================================================

    for job in jobs:

        postgres_cursor.execute("""
            INSERT INTO jobs (
                id,
                title,
                company,
                location,
                description,
                expiry_date,
                long_description,
                company_id,
                url,
                date_found
            )
            VALUES (
                %s, %s, %s, %s, %s,
                %s, %s, %s, %s, %s
            )
            ON CONFLICT (id)
            DO UPDATE SET
                title = EXCLUDED.title,
                company = EXCLUDED.company,
                location = EXCLUDED.location,
                description = EXCLUDED.description,
                expiry_date = EXCLUDED.expiry_date,
                long_description = EXCLUDED.long_description,
                company_id = EXCLUDED.company_id,
                url = EXCLUDED.url,
                date_found = EXCLUDED.date_found
        """, tuple(job))


    # ========================================================
    # RESET IDENTITY COUNTERS
    # ========================================================

    postgres_cursor.execute("""
        SELECT setval(
            pg_get_serial_sequence(
                'companies',
                'company_id'
            ),
            COALESCE(
                (SELECT MAX(company_id) FROM companies),
                1
            ),
            (SELECT COUNT(*) > 0 FROM companies)
        );
    """)


    postgres_cursor.execute("""
        SELECT setval(
            pg_get_serial_sequence(
                'jobs',
                'id'
            ),
            COALESCE(
                (SELECT MAX(id) FROM jobs),
                1
            ),
            (SELECT COUNT(*) > 0 FROM jobs)
        );
    """)


    # ========================================================
    # COMMIT
    # ========================================================

    postgres_conn.commit()


    # ========================================================
    # VERIFY
    # ========================================================

    postgres_cursor.execute("""
        SELECT COUNT(*) FROM companies;
    """)

    company_count = postgres_cursor.fetchone()[0]


    postgres_cursor.execute("""
        SELECT COUNT(*) FROM jobs;
    """)

    job_count = postgres_cursor.fetchone()[0]


    print()
    print("============================================")
    print(" MIGRATION COMPLETE")
    print("============================================")
    print(f"Companies migrated: {company_count}")
    print(f"Jobs migrated:      {job_count}")
    print("============================================")
    print()


except Exception as error:

    postgres_conn.rollback()

    print()
    print("============================================")
    print(" MIGRATION FAILED")
    print("============================================")
    print(error)
    print("============================================")
    print()

    raise


finally:

    postgres_cursor.close()
    postgres_conn.close()

    sqlite_cursor.close()
    sqlite_conn.close()
