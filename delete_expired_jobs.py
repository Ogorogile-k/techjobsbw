import sqlite3
from datetime import datetime

conn = sqlite3.connect("jobs.db")
cursor = conn.cursor()

cursor.execute("""
DELETE FROM jobs
WHERE DATE(expiry_date) < DATE('now')
""")

deleted = cursor.rowcount

conn.commit()
conn.close()

print(f"[{datetime.now()}] Deleted {deleted} expired job(s).")