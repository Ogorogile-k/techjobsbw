def download(url):

    try:

        with sync_playwright() as p:

            browser = p.chromium.launch(

                headless=True

            )

            page = browser.new_page()

            page.goto(

                url,

                wait_until="domcontentloaded",

                timeout=30000

            )



            ################################################
            # COOKIE BANNERS
            ################################################

            try:

                page.get_by_role(

                    "button",

                    name="Accept"

                ).click(

                    timeout=2000

                )

            except:

                pass



            ################################################
            # GOOGLE VIGNETTE
            ################################################

            if "#google_vignette" in page.url:

                clean = page.url.replace(

                    "#google_vignette",

                    ""

                )

                page.goto(

                    clean,

                    wait_until="domcontentloaded"

                )



            html = page.content()

            browser.close()

            return html



    except Exception as e:

        print(

            "Download failed:",

            url

        )

        print(e)

        return None

