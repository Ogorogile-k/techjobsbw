def parse_date(text):

    """
    Attempts to convert a string into a datetime.

    Returns None if unsuccessful.
    """

    if text is None:

        return None

    text = text.strip()

    if text == "":

        return None


    formats = [

        "%d %B %Y",
        "%d %b %Y",

        "%Y-%m-%d",

        "%d/%m/%Y",
        "%d-%m-%Y"

    ]


    for fmt in formats:

        try:

            return datetime.strptime(

                text,

                fmt

            )

        except:

            pass


    return None



####################################################
# EXPIRED?
####################################################

def is_expired(closing_date):

    """
    Returns True if the vacancy has expired.
    """

    if closing_date is None:

        return False


    date = parse_date(

        closing_date

    )

    if date is None:

        return False


    today = datetime.today()


    return date.date() < today.date()



