def scrape_jobsbotswana_job(url):

    html = download(

        url

    )

    if html is None:

        return


    soup = BeautifulSoup(

        html,

        "lxml"

    )


    ################################################
    # Title
    ################################################

    title = ""

    h1 = soup.find("h1")

    if h1:

        title = h1.get_text(

            strip=True

        )


    ################################################
    # Entire page text
    ################################################

    text = soup.get_text(

        "\n",

        strip=True

    )


    ################################################
    # Company
    ################################################

    company = ""

    m = re.search(

        r"Company\s*:?\s*(.+)",

        text,

        re.I

    )

    if m:

        company = m.group(1).split("\n")[0].strip()


    ################################################
    # Location
    ################################################

    location = ""

    m = re.search(

        r"Location\s*:?\s*(.+)",

        text,

        re.I

    )

    if m:

        location = m.group(1).split("\n")[0].strip()


    ################################################
    # Closing Date
    ################################################

    expiry = ""

    m = re.search(

        r"(Closing Date|Deadline)\s*:?\s*(.+)",

        text,

        re.I

    )

    if m:

        expiry = m.group(2).split("\n")[0].strip()


    ################################################
    # Skip expired
    ################################################

    if is_expired(

        expiry

    ):

        SUMMARY["expired"] += 1

        delete_job(

            url

        )

        return


    ################################################
    # Duplicate?
    ################################################

    if job_exists(

        url

    ):

        SUMMARY["duplicates"] += 1

        return


    ################################################
    # Description
    ################################################

    description = text[:500]


    ################################################
    # Save
    ################################################

    job = {

        "title": title,

        "company": company,

        "location": location,

        "description": description,

        "long_description": text,

        "expiry_date": expiry,

        "url": url

    }


    save_job(

        job

    )


    SUMMARY["saved"] += 1


    print_job(

        job

    )

