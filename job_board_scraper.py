def scrape_jobsbotswana():

    print()

    print("=" * 60)

    print("Scanning JobsBotswana...")

    print("=" * 60)


    html = download(

        "https://jobsbotswana.info/list/jobs/"

    )

    if html is None:

        return


    soup = BeautifulSoup(

        html,

        "lxml"

    )


    ################################################
    # Find every vacancy link
    ################################################

    links = []


    for link in soup.find_all(

        "a",

        href=True

    ):

        href = urljoin(

            "https://jobsbotswana.info/",

            link["href"]

        )


        ################################################
        # Job pages only
        ################################################

        if "/job/" not in href.lower():

            continue


        if href not in links:

            links.append(

                href

            )


    ################################################
    # Visit every vacancy
    ################################################

    for url in links:

        SUMMARY["scanned"] += 1

        scrape_jobsbotswana_job(

            url

        )

