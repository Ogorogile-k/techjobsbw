####################################################
# CHECK WHETHER JOB EXISTS
####################################################

def job_exists(url):

    conn = connect_database()

    cur = conn.cursor()

    cur.execute(

        """

        SELECT id

        FROM jobs

        WHERE url = ?

        """,

        (

            url,

        )

    )

    exists = cur.fetchone()

    conn.close()

    return exists is not None



####################################################
# DELETE JOB
####################################################

def delete_job(url):

    conn = connect_database()

    cur = conn.cursor()

    cur.execute(

        """

        DELETE

        FROM jobs

        WHERE url = ?

        """,

        (

            url,

        )

    )

    conn.commit()

    conn.close()



