def save_job(job):

    """
    Inserts a new job into jobs.db.

    Ignores duplicates.

    Ignores expired jobs.
    """

    if job_exists(

        job["url"]

    ):

        return


    if is_expired(

        job["expiry_date"]

    ):

        return


    conn = connect_database()

    cur = conn.cursor()


    cur.execute(

        """

        INSERT INTO jobs(

            title,

            company,

            location,

            description,

            expiry_date,

            long_description,

            company_id,

            url,

            date_found

        )

        VALUES(

            ?,?,?,?,?,?,?,?,?

        )

        """,

        (

            job["title"],

            job["company"],

            job["location"],

            job["description"],

            job["expiry_date"],

            job["long_description"],

            None,

            job["url"],

            datetime.today().strftime(

                "%Y-%m-%d"

            )

        )

    )


    conn.commit()

    conn.close()



