def get_db_connection():

    database_url = os.environ.get("DATABASE_URL")

    if not database_url:

        raise RuntimeError(
            "DATABASE_URL environment variable is not set."
        )

    conn = psycopg2.connect(
        database_url,
        cursor_factory=RealDictCursor
    )

    return conn


