@app.route("/companies")
def companies():

    conn = get_db_connection()
    cursor = conn.cursor()

    cursor.execute("""
        SELECT
            c.company_id,
            c.name,
            COUNT(j.id) AS job_count

        FROM companies c

        INNER JOIN jobs j
            ON c.company_id = j.company_id

        GROUP BY
            c.company_id,
            c.name

        ORDER BY
            c.name
    """)

    companies = cursor.fetchall()

    cursor.close()
    conn.close()

    return render_template(
        "companies.html",
        companies=companies
    )


