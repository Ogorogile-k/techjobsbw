from flask import Flask, render_template, jsonify
import sqlite3

app = Flask(__name__)

DATABASE = "jobs.db"


# ============================================================
# DATABASE CONNECTION
# ============================================================

def get_db_connection():

    conn = sqlite3.connect(DATABASE)

    conn.row_factory = sqlite3.Row

    return conn


# ============================================================
# ALL JOBS
# ============================================================

@app.route("/")
def home():

    conn = get_db_connection()

    cursor = conn.cursor()

    cursor.execute("""
        SELECT *
        FROM jobs
        ORDER BY date_found DESC
    """)

    jobs = cursor.fetchall()

    conn.close()

    return render_template(
        "techjobs.html",
        jobs=jobs
    )


# ============================================================
# ALL JOBS JSON API
# ============================================================

@app.route("/jobs")
def get_jobs():

    conn = get_db_connection()

    cursor = conn.cursor()

    cursor.execute("""
        SELECT *
        FROM jobs
        ORDER BY date_found DESC
    """)

    jobs = cursor.fetchall()

    conn.close()

    return jsonify([
        dict(job)
        for job in jobs
    ])


# ============================================================
# BY COMPANY
# ============================================================

@app.route("/companies")
def companies():

    conn = get_db_connection()

    cursor = conn.cursor()

    cursor.execute("""
        SELECT
            c.company_id,
            c.name,
            COUNT(j.id) AS job_count

        FROM companies c

        INNER JOIN jobs j
            ON c.company_id = j.company_id

        GROUP BY
            c.company_id,
            c.name

        ORDER BY
            c.name
    """)

    companies = cursor.fetchall()

    conn.close()

    return render_template(
        "companies.html",
        companies=companies
    )


