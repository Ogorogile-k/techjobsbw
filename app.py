@app.route("/company/<int:company_id>")
def company_jobs(company_id):

    conn = get_db_connection()

    cursor = conn.cursor()

    # --------------------------------------------------------
    # Get company
    # --------------------------------------------------------

    cursor.execute("""
        SELECT
            company_id,
            name,
            industry,
            website,
            email,
            phone,
            headquarters,
            logo,
            description

        FROM companies

        WHERE company_id = ?
    """, (company_id,))

    company = cursor.fetchone()

    if company is None:

        conn.close()

        return "Company not found", 404


    # --------------------------------------------------------
    # Get company's jobs
    # --------------------------------------------------------

    cursor.execute("""
        SELECT *
        FROM jobs

        WHERE company_id = ?

        ORDER BY date_found DESC
    """, (company_id,))

    jobs = cursor.fetchall()

    conn.close()

    return render_template(
        "company.html",
        company=company,
        jobs=jobs
    )


