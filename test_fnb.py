from playwright.sync_api import sync_playwright
from urllib.parse import urljoin
import re


FNB_URL = (
    "https://firstrand.wd3.myworkdayjobs.com/"
    "FRB?locationCountry="
    "db69bdbc446c11de98360015c5e6daf6"
)


with sync_playwright() as p:

    browser = p.chromium.launch(
        headless=False
    )

    page = browser.new_page()

    print()
    print("=" * 60)
    print("FNB WORKDAY TEST")
    print("=" * 60)

    print()
    print("Opening FNB Workday...")

    page.goto(
        FNB_URL,
        wait_until="domcontentloaded",
        timeout=120000
    )

    print("Page loaded.")

    # Give Workday time to render
    page.wait_for_timeout(10000)

    print()
    print("Looking for job links...")

    job_links = []

    links = page.locator("a").all()

    for link in links:

        try:

            text = link.inner_text().strip()

            href = link.get_attribute("href")

            if not href:
                continue

            print()
            print("LINK:")
            print("TITLE:", text)
            print("URL:", href)

            if "/job/Gaborone/" not in href:
                continue

            job_url = urljoin(
                FNB_URL,
                href
            )

            if job_url not in job_links:

                job_links.append(job_url)

        except Exception:
            continue


    print()
    print("=" * 60)
    print("BOTSWANA JOB LINKS FOUND:", len(job_links))
    print("=" * 60)


    # ========================================================
    # OPEN EACH JOB
    # ========================================================

    for job_url in job_links:

        print()
        print("=" * 60)
        print("OPENING JOB")
        print("=" * 60)

        print(job_url)

        job_page = browser.new_page()

        job_page.goto(
            job_url,
            wait_until="domcontentloaded",
            timeout=120000
        )

        # Workday needs time to render the details
        job_page.wait_for_timeout(10000)

        print()
        print("FINAL URL:")
        print(job_page.url)

        print()
        print("PAGE TEXT:")
        print("-" * 60)

        text = job_page.locator(
            "body"
        ).inner_text()

        print(text[:20000])

        print("-" * 60)

        # ====================================================
        # TITLE
        # ====================================================


        title = ""

        lines = [
          line.strip()
            for line in text.splitlines()
            if line.strip()
        ]

        for i, line in enumerate(lines):

           if line.endswith("page is loaded"):

               if i + 1 < len(lines):

                   title = lines[i + 1]

               break



        # ====================================================
        # LOCATION
        # ====================================================

        location = ""

        match = re.search(
            r"locations\s*\n\s*([^\n]+)",
            text,
            re.IGNORECASE
        )

        if match:

            location = match.group(1).strip()


        # ====================================================
        # CLOSING DATE
        # ========================================================

        closing_date = ""

        match = re.search(
            r"End Date:\s*([A-Za-z]+\s+\d{1,2},\s+\d{4})",
            text,
            re.IGNORECASE
        )

        if match:

            closing_date = match.group(1).strip()


        # ====================================================
        # DESCRIPTION
        # ========================================================

        description = ""

        if "Job Description" in lines:

            start = lines.index(
                "Job Description"
            ) + 1

            if "Qualifications" in lines:

                end = lines.index(
                    "Qualifications"
                )

                description = "\n".join(
                    lines[start:end]
                ).strip()

            else:

                description = "\n".join(
                    lines[start:]
                ).strip()


        # ====================================================
        # EXTRACTED DATA
        # ========================================================

        print()
        print("=" * 60)
        print("EXTRACTED JOB DATA")
        print("=" * 60)

        print()
        print("TITLE:")
        print(title)

        print()
        print("LOCATION:")
        print(location)

        print()
        print("CLOSING DATE:")
        print(closing_date)

        print()
        print("DESCRIPTION:")
        print(description[:3000])

        job_page.close()


    print()
    print("=" * 60)
    print("TEST FINISHED")
    print("=" * 60)

    input(
        "Press ENTER to close the browser..."
    )

    browser.close()