def find_careers_page(homepage):

    page = download(homepage)

    if page is None:

        return None

    soup = BeautifulSoup(

        page["content"],

        "lxml"

    )

    for link in soup.find_all(

        "a",

        href=True

    ):

        href = link["href"]

        text = link.get_text(

            " ",

            strip=True

        ).lower()

        combined = (

            text +

            " " +

            href.lower()

        )

        for keyword in JOB_KEYWORDS:

            if keyword in combined:

                return urljoin(

                    homepage,

                    href

                )

    return homepage


