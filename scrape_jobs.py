def extract_links(base_url):

    page = download(base_url)

    if page is None:

        return []

    soup = BeautifulSoup(

        page["content"],

        "lxml"

    )

    links = []

    seen = set()

    for tag in soup.find_all(

        "a",

        href=True

    ):

        href = tag["href"].strip()

        if should_skip_url(href):

            continue

        url = urljoin(

            base_url,

            href

        )

        if should_skip_url(url):

            continue

        lower = url.lower()

        #
        # Only keep likely job links.
        #

        if not (

            any(

                keyword in lower

                for keyword in JOB_KEYWORDS

            )

            or

            lower.endswith(".pdf")

        ):

            continue

        #
        # Remove duplicates.
        #

        if url in seen:

            continue

        seen.add(url)

        links.append(url)

    return links

