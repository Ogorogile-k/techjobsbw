def scrape_botswanapost(company):

    print("Checking BotswanaPost...")

    careers = "https://botswanapost.post/careers"

    page = download(careers)

    if page is None:
        return

    soup = BeautifulSoup(
        page["content"],
        "lxml"
    )

    rows = soup.find_all("tr")

    seen = set()

    for row in rows:

        # ------------------------------------------------
        # TITLE
        # ------------------------------------------------

        title_cell = row.find(
            "td",
            class_="views-field-title"
        )

        # ------------------------------------------------
        # CLOSING DATE
        # ------------------------------------------------

        date_cell = row.find(
            "td",
            class_="views-field-field__closing-date"
        )

        # ------------------------------------------------
        # FILE LINK
        # ------------------------------------------------

        file_cell = row.find(
            "td",
            class_="views-field-field-file-"
        )

        #
        # The row must contain all three fields.
        #

        if (
            title_cell is None
            or date_cell is None
            or file_cell is None
        ):
            continue

        title = title_cell.get_text(
            " ",
            strip=True
        )

        closing_date_text = date_cell.get_text(
            " ",
            strip=True
        )

        link = file_cell.find(
            "a",
            href=True
        )

        if link is None:
            continue

        href = link.get(
            "href",
            ""
        ).strip()

        if not href:
            continue

        url = urljoin(
            careers,
            href
        )

        # ------------------------------------------------
        # ONLY PROCESS DOCUMENTS
        # ------------------------------------------------

        lower = url.lower()

        if not (
            lower.endswith(".pdf")
            or lower.endswith(".doc")
            or lower.endswith(".docx")
        ):
            continue

        # ------------------------------------------------
        # AVOID DUPLICATES
        # ------------------------------------------------

        if url in seen:
            continue

        seen.add(url)

        print()
        print("Checking BotswanaPost vacancy:")
        print(url)

        print()
        print("Careers page title:")
        print(title)

        print()
        print("Careers page closing date:")
        print(closing_date_text)

        # ------------------------------------------------
        # NORMALIZE CLOSING DATE
        # ------------------------------------------------

        closing_date = ""

        date_formats = [
            "%b %d, %Y",
            "%B %d, %Y",
            "%d %b %Y",
            "%d %B %Y"
        ]

        for date_format in date_formats:

            try:

                closing_date = datetime.strptime(
                    closing_date_text,
                    date_format
                ).strftime(
                    "%Y-%m-%d"
                )

                break

            except ValueError:

                continue

        # ------------------------------------------------
        # INVALID DATE
        # ------------------------------------------------

        if not closing_date:

            print(
                "Warning: could not parse BotswanaPost "
                "closing date:",
                closing_date_text
            )

        else:

            print(
                "Normalized closing date:",
                closing_date
            )

            # ------------------------------------------------
            # CHECK WHETHER THE JOB HAS EXPIRED
            # ------------------------------------------------

            try:

                expiry = datetime.strptime(
                    closing_date,
                    "%Y-%m-%d"
                ).date()

                today = datetime.now().date()

                if expiry < today:

                    print(
                        "Skipping expired BotswanaPost vacancy:"
                    )

                    print(
                        f"{title} → expired {closing_date}"
                    )

                    continue

            except ValueError:

                print(
                    "Warning: could not compare "
                    "BotswanaPost closing date."
                )

        # ------------------------------------------------
        # DOWNLOAD VACANCY DOCUMENT
        # ------------------------------------------------

        vacancy_page = download(url)

        if vacancy_page is None:
            continue

        text = extract_text(
            vacancy_page
        )

        if not text:
            continue

        # ------------------------------------------------
        # QUICK VACANCY FILTER
        # ------------------------------------------------

        lower_text = text.lower()

        indicators = [
            "vacancy",
            "vacancies",
            "job summary",
            "position requirements",
            "qualifications",
            "application instructions",
            "applications"
        ]

        if not any(
            indicator in lower_text
            for indicator in indicators
        ):
            continue

        # ------------------------------------------------
        # GEMINI
        # ------------------------------------------------

        result = classify_job(
            text,
            url
        )

        if not result.get(
            "is_job",
            False
        ):
            continue

        # ------------------------------------------------
        # CAREERS PAGE IS THE AUTHORITATIVE DATE
        # ------------------------------------------------

        if closing_date:

            result["closing_date"] = closing_date

        # ------------------------------------------------
        # USE CAREERS PAGE TITLE IF GEMINI MISSES IT
        # ------------------------------------------------

        if not result.get("title"):

            result["title"] = title

        # ------------------------------------------------
        # PRINT JOB
        # ------------------------------------------------

        print_job(
            company,
            result,
            url
        )

        # ------------------------------------------------
        # SAVE JOB
        # ------------------------------------------------

        save_job(
            company,
            result,
            url
        )




