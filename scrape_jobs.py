def scrape_bpc(company):

    print("Checking Botswana Power Corporation...")

    url = "https://careers.bpc.bw/search"

    page = download(url)

    if page is None:

        return

    soup = BeautifulSoup(

        page["content"],

        "lxml"

    )

    #
    # BPC exposes vacancy cards directly.
    #
    # Therefore we don't need Gemini here.
    #

    seen = set()

    for link in soup.find_all(

        "a",

        href=True

    ):

        href = link.get(

            "href",

            ""

        )

        if "/job/" not in href:

            continue

        job_url = urljoin(

            url,

            href

        )

        if job_url in seen:

            continue

        seen.add(

            job_url

        )

        #
        # Visit the job page.
        #

        job_page = download(

            job_url

        )

        if job_page is None:

            continue

        job_soup = BeautifulSoup(

            job_page["content"],

            "lxml"

        )

        text = job_soup.get_text(

            " ",

            strip=True

        )

        #
        # Extract title.
        #

        title = ""

        h1 = job_soup.find("h1")

        if h1:

            title = h1.get_text(

                strip=True

            )

        #
        # Extract location.
        #

        location = ""

        match = re.search(

            r"Location[:\s]+([A-Za-z ,&-]+)",

            text,

            re.IGNORECASE

        )

        if match:

            location = match.group(1).strip()

        #
        # Extract closing date.
        #

        closing = ""

        patterns = [

            r"Closing Date[:\s]+([^\n]+)",

            r"Closing date[:\s]+([^\n]+)",

            r"Apply before[:\s]+([^\n]+)"

        ]

        for pattern in patterns:

            match = re.search(

                pattern,

                text,

                re.IGNORECASE

            )

            if match:

                closing = match.group(1).strip()

                break

        job = {

            "title": title,

            "location": location,

            "closing_date": closing,

            "description": text[:5000],

            "reason": "BPC structured vacancy"

        }

        print_job(

            company,

            job,

            job_url

        )

        save_job(

            company,

            job,

            job_url

        )

