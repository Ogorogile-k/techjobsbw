def normalize_expiry_date_with_gemini(date_string):

    """
    Use Gemini to normalize a closing date only
    when the local Python parser cannot understand it.

    Returns:

        YYYY-MM-DD

    or:

        ""

    if no definite date can be determined.
    """

    if not date_string:
        return ""


    prompt = f"""
You are processing a job vacancy.

Convert the following job closing/expiry date
into the format YYYY-MM-DD.

Closing date information:
{date_string}

Rules:

1. Return ONLY a date in YYYY-MM-DD format.
2. Do not return any explanation.
3. Do not use markdown.
4. If there is no definite calendar date,
   return UNKNOWN.
5. Do not guess a date.
"""


    try:

        response = client.models.generate_content(
            model=MODEL,
            contents=prompt
        )


        result = response.text.strip()


        if result.upper() == "UNKNOWN":

            return ""


        # ------------------------------------------------
        # Look for a YYYY-MM-DD date in Gemini's response
        # ------------------------------------------------

        match = re.search(
            r'\b\d{4}-\d{2}-\d{2}\b',
            result
        )


        if not match:

            return ""


        normalized_date = match.group(0)


        # ------------------------------------------------
        # Verify that the returned date is valid
        # ------------------------------------------------

        try:

            datetime.strptime(
                normalized_date,
                "%Y-%m-%d"
            )

        except ValueError:

            return ""


        return normalized_date


    except Exception as e:

        print()
        print(
            "Warning: Gemini expiry-date "
            "normalization failed."
        )

        print(e)

        print(
            "The job will still be saved "
            "without an expiry date."
        )

        print()

        return ""


