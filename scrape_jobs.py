def should_skip_url(url):

    if not url:

        return True


    url = url.strip()


    for prefix in IGNORE_PREFIXES:

        if url.startswith(prefix):

            return True


    lower = url.lower()


    for word in IGNORE_URL_KEYWORDS:

        if word in lower:

            return True


    return False


